export const GUEST_TEXT: Record<Lang, Text> = { en, es, fr, ht };

export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem("seating4u_lang");
    if (saved === "en" || saved === "es" || saved === "fr" || saved === "ht") return saved;
  } catch {
    /* ignore */
  }
  const n = (typeof navigator !== "undefined" ? navigator.language : "en").toLowerCase();
  if (n.startsWith("es")) return "es";
  if (n.startsWith("ht")) return "ht";
  if (n.startsWith("fr")) return "fr";
  return "en";
}
